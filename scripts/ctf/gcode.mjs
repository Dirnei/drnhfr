const ADVANCE = 6;

export function strokesFor(text) {
  const strokes = [];
  [...text].forEach((char, index) => {
    const glyph = GLYPHS[char];
    if (!glyph) throw new Error(`no glyph for ${JSON.stringify(char)}`);
    for (const stroke of glyph) strokes.push(stroke.map(([x, y]) => [x + index * ADVANCE, y]));
  });
  return strokes;
}

export function textToGcode(text, { scale = 2, feed = 1200, power = 1000 } = {}) {
  const at = ([x, y]) => `X${(x * scale).toFixed(2)} Y${((y + 3) * scale).toFixed(2)}`;
  const lines = ['G21', 'G90', 'M5', `F${feed}`];
  for (const stroke of strokesFor(text)) {
    lines.push(`G0 ${at(stroke[0])}`, `M3 S${power}`);
    for (const point of stroke.slice(1)) lines.push(`G1 ${at(point)}`);
    lines.push('M5');
  }
  lines.push('G0 X0 Y0', 'M2');
  return lines.join('\n') + '\n';
}

